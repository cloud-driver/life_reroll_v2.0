class UserError(ValueError):
    def __init__(self, code, message, details=None):
        super().__init__(code)
        self.message = message
        self.details = details


def message_for(code):
    return MESSAGES.get(code, '操作未能完成，請稍後再試；若持續發生，請聯絡專案團隊。')


def response(error, messages=None, statuses=None):
    code = str(error)
    if not re.fullmatch(r'[A-Z][A-Z0-9_]{0,63}', code):
        code = 'SERVICE_UNAVAILABLE'
    message = error.message if isinstance(error, UserError) else (messages or MESSAGES).get(code, message_for(code))
    value = {'code': code, 'message': message}
    if isinstance(error, UserError) and error.details:
        value['details'] = error.details
    return JSONResponse({'data': None, 'error': value}, status_code=(statuses or STATUSES).get(code, 503))
